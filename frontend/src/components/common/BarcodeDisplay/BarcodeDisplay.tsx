
import { useEffect, useMemo, useRef } from "react";

import {
  Box,
  Button,
  ButtonGroup,
  Typography,
} from "@mui/material";

import {
  DownloadOutlined,
  ErrorOutlined,
} from "@mui/icons-material";

import JsBarcode from "jsbarcode";

export type BarcodeFormat =
  | "CODE128"
  | "EAN13"
  | "EAN8"
  | "UPC";

export interface BarcodeDisplayProps {
  value: string;
  format?: BarcodeFormat;
  width?: number;
  height?: number;
  displayValue?: boolean;
  lineColor?: string;
  background?: string;
  fontSize?: number;
  margin?: number;
  showDownload?: boolean;
  filename?: string;
  onError?: (message: string) => void;
}

function BarcodeDisplay({
  value,
  format = "CODE128",
  width = 2,
  height = 80,
  displayValue = true,
  lineColor = "#000000",
  background = "#ffffff",
  fontSize = 14,
  margin = 10,
  showDownload = true,
  filename = "barcode",
  onError,
}: BarcodeDisplayProps) {
  const svgRef = useRef<SVGSVGElement | null>(null);

  // Validate and generate the barcode in memory.
  // No React state updates are needed.
  const barcodeResult = useMemo(() => {
    const svg = document.createElementNS(
      "http://www.w3.org/2000/svg",
      "svg"
    );

    try {
      if (!value.trim()) {
        throw new Error("Barcode value is required.");
      }

      JsBarcode(svg, value, {
        format,
        width,
        height,
        displayValue,
        lineColor,
        background,
        fontSize,
        margin,
      });

      return {
        svgMarkup: svg.innerHTML,
        attributes: Array.from(svg.attributes).map(
          (attribute) => [
            attribute.name,
            attribute.value,
          ] as const
        ),
        error: null as string | null,
      };
    } catch (err) {
      return {
        svgMarkup: "",
        attributes: [] as ReadonlyArray<
          readonly [string, string]
        >,
        error:
          err instanceof Error
            ? err.message
            : "Unable to generate barcode.",
      };
    }
  }, [
    value,
    format,
    width,
    height,
    displayValue,
    lineColor,
    background,
    fontSize,
    margin,
  ]);

  // Synchronize the generated SVG with the DOM.
  useEffect(() => {
    const svg = svgRef.current;

    if (!svg) {
      return;
    }

    svg.replaceChildren();

    for (const attribute of Array.from(
      svg.attributes
    )) {
      svg.removeAttribute(attribute.name);
    }

    if (barcodeResult.error) {
      return;
    }

    // Barcode SVG markup is generated by JsBarcode
    // from the validated input, not supplied as HTML.
    svg.innerHTML = barcodeResult.svgMarkup;

    for (const [name, attributeValue] of
      barcodeResult.attributes) {
      svg.setAttribute(name, attributeValue);
    }
  }, [barcodeResult]);

  // Report errors outside the rendering phase.
  useEffect(() => {
    if (barcodeResult.error) {
      onError?.(barcodeResult.error);
    }
  }, [barcodeResult.error, onError]);

  const handleDownloadSVG = () => {
    const svg = svgRef.current;

    if (!svg || barcodeResult.error) {
      return;
    }

    const serializer = new XMLSerializer();

    const svgString =
      serializer.serializeToString(svg);

    const blob = new Blob([svgString], {
      type: "image/svg+xml;charset=utf-8",
    });

    const url = URL.createObjectURL(blob);

    const anchor = document.createElement("a");

    anchor.href = url;
    anchor.download = `${filename}.svg`;

    anchor.click();

    URL.revokeObjectURL(url);
  };

  const handleDownloadPNG = () => {
    const svg = svgRef.current;

    if (!svg || barcodeResult.error) {
      return;
    }

    const serializer = new XMLSerializer();

    const svgString =
      serializer.serializeToString(svg);

    const blob = new Blob([svgString], {
      type: "image/svg+xml;charset=utf-8",
    });

    const url = URL.createObjectURL(blob);

    const image = new Image();

    image.onload = () => {
      const canvas =
        document.createElement("canvas");

      const scale = 3;

      canvas.width = image.width * scale;
      canvas.height = image.height * scale;

      const context = canvas.getContext("2d");

      if (!context) {
        URL.revokeObjectURL(url);
        return;
      }

      context.scale(scale, scale);
      context.drawImage(image, 0, 0);

      const pngUrl =
        canvas.toDataURL("image/png");

      const anchor =
        document.createElement("a");

      anchor.href = pngUrl;
      anchor.download = `${filename}.png`;

      anchor.click();

      URL.revokeObjectURL(url);
    };

    image.onerror = () => {
      URL.revokeObjectURL(url);
    };

    image.src = url;
  };

  return (
    <Box
      sx={{
        display: "flex",
        flexDirection: "column",
        alignItems: "center",
        gap: 1.5,
      }}
    >
      {barcodeResult.error && (
        <Box
          sx={{
            display: "flex",
            alignItems: "center",
            gap: 1,
            color: "error.main",
            p: 2,
          }}
        >
          <ErrorOutlined fontSize="small" />

          <Typography variant="body2">
            {barcodeResult.error}
          </Typography>
        </Box>
      )}

      {!barcodeResult.error && (
        <Box
          sx={{
            maxWidth: "100%",
            overflowX: "auto",
            textAlign: "center",
          }}
        >
          <svg
            ref={svgRef}
            role="img"
            aria-label={`Barcode ${value}`}
          />
        </Box>
      )}

      {showDownload && !barcodeResult.error && (
        <ButtonGroup
          size="small"
          variant="outlined"
        >
          <Button
            startIcon={<DownloadOutlined />}
            onClick={handleDownloadPNG}
          >
            PNG
          </Button>

          <Button
            startIcon={<DownloadOutlined />}
            onClick={handleDownloadSVG}
          >
            SVG
          </Button>
        </ButtonGroup>
      )}
    </Box>
  );
}

export default BarcodeDisplay;
